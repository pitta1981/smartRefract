    private void jRadioButton4ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jRadioButton4ItemStateChanged
        int maxXY = dati_sismici.stesa.get(0).ch / 4;
        tv_Draw.tV2A = new double[maxXY][];
        jSpinner1.setValue(tv_Draw.sel2);
        if (jRadioButton2.isSelected()) {
            GRM grm = new GRM();
            double tAB = Math.max(dati_sismici.man_Phant_and[1].tAB, dati_sismici.man_Phant_rit[1].tAB);
            for (int i = 0; i < maxXY; i++) {

                tv_Draw.tV2A[i] = grm.compute_tV(dati_sismici.man_Phant_and[1], dati_sismici.man_Phant_rit[1], tAB, dati_sismici.stesa.get(0).spaz * i);
                //dati_sismici.DTTv(1, ((FirstBrakeList) dati_sismici.stesa.get(0)).spaz * i);
                for (int j = 0; j < tv_Draw.tV2A[i].length; j++) {
                    tv_Draw.tV2A[i][j] = tv_Draw.tV2A[i][j];// + (i * 15);

                }
            }

        } else {
            for (int i = 0; i < tv_Draw.tV2A.length; i++) {

                tv_Draw.tV2A[i] = dati_sismici.DTTv(2, ( dati_sismici.stesa.get(0)).spaz * i);
                for (int j = 0; j < tv_Draw.tV2A[i].length; j++) {
                    tv_Draw.tV2A[i][j] = tv_Draw.tV2A[i][j]; //+ (i * 15);

                }
            }
        }
        tv_Draw.tV1 = null;
        tv_Draw.tV2 = dati_sismici.Tv2;
        tv_Draw.spaz = dati_sismici.stesa.get(0).spaz;
        tv_Draw.invalidate();
        tv_Draw.repaint();
    }//GEN-LAST:event_jRadioButton4ItemStateChanged

