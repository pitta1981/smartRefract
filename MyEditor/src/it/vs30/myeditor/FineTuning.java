    private void button_saveTxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button_saveTxActionPerformed
        // TODO add your handling code here:
        int i = 0;
        int chanel = dati_sismici.stesa.get(0).ch;
        dati_sismici.init_man_phantoming(chanel, dati_sismici.stesa,false);

        i = 0;
        for (JShot shot : dati_sismici.shots) {
            i++;

            for (FB_set fbs : shot.FB_sets) {
                if (fbs.layer == (edit_index + 2) && fbs.used) {
                    for (FirstBrake fb : fbs.fb) {
                        if (fbs.dir > 0) {
                            FirstBrakeList fbl = dati_sismici.man_Phant_and[fbs.layer - 2];
                            if (fbl.fb[fb.chan].offset >= Math.abs(fb.posx - fbs.xshot)) {
                                //man_Phant_and.fb[fb.chan] = fb;
                                fbl.fb[fb.chan].time = fb.time + fbs.shift;
                                fbl.fb[fb.chan].offset = Math.abs(fb.posx - fbs.xshot);
                            }
                        } else {
                            FirstBrakeList fbl = dati_sismici.man_Phant_rit[fbs.layer - 2];
                            if (fbl.fb[fb.chan].offset >= Math.abs(fb.posx - fbs.xshot)) {
                                //man_Phant_and.fb[fb.chan] = fb;
                                fbl.fb[fb.chan].time = fb.time + fbs.shift;
                                fbl.fb[fb.chan].offset = Math.abs(fb.posx - fbs.xshot);
                            }
                        }
                    }

                    //break;
                }
            }
        }
        fillTT(dati_sismici.man_Phant_and[edit_index].fb);
        fillTT(dati_sismici.man_Phant_rit[edit_index].fb);
        dati_sismici.man_Phant_and[edit_index].scoppio = dati_sismici.stesa.get(base_shot[0]).scoppio;
        dati_sismici.man_Phant_rit[edit_index].scoppio = dati_sismici.stesa.get(base_shot[1]).scoppio;
        dati_sismici.man_Phant_and[edit_index].tAB = dati_sismici.man_Phant_and[edit_index].getT(dati_sismici.stesa.get(base_shot[1]).scoppio);
        dati_sismici.man_Phant_rit[edit_index].tAB = dati_sismici.man_Phant_rit[edit_index].getT(dati_sismici.stesa.get(base_shot[0]).scoppio);
        init_status();
//        return;
    }//GEN-LAST:event_button_saveTxActionPerformed

