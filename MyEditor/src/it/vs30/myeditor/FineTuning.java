    public FineTuning(Indagine proj) {
        initComponents();

        tv_Draw = new JtV_draw();
        tg_Draw = new JtV_draw();
        jPanel10.add(tv_Draw);
        jPanel13.add(tg_Draw);
        tv_Draw.sel1 = (int) (proj.xy / proj.stesa.get(0).spaz);
        tv_Draw.sel2 = (int) (proj.xy2 / proj.stesa.get(0).spaz);

        Color[] color = new Color[255];
        for (int i = 0; i < 255; i++) {
            color[i] = new Color((int) (155 * Math.random()), (int) (185 * Math.random()), (int) (200 * Math.random()));
        }
        color[1] = new Color(50, 175, 165);
        color[2] = new Color(220, 40, 40);
        proj.buildShots();

        Bool[] phnt_visible = new Bool[3];
        man_phnt_visible = new Bool[3];
        for (int i = 0; i < 3; i++) {
            man_phnt_visible[i] = new Bool();
            phnt_visible[i] = new Bool();
            is_visible[i] = new Bool();
            layer_edit[i] = new Bool();
            layer_edit[i].setValue(false);
        }

        JCustom_layer_chooser[] clc = new JCustom_layer_chooser[2];
        clc[0] = new JCustom_layer_chooser("Layer1", clc, 0, phnt_visible[1]);


        clc[1] = new JCustom_layer_chooser("Layer2", clc, 1, phnt_visible[2]);
        clc[0].jRadioButton1.setEnabled(false);
        clc[1].jRadioButton1.setEnabled(false);
        jPanel6.add(clc[0]);
        jPanel6.add(clc[1]);
        JCustom_layer_chooser[] man_phant_chooser = new JCustom_layer_chooser[2];
        man_phant_chooser[0] = new JCustom_layer_chooser("Layer1", man_phant_chooser, 0, man_phnt_visible[1]);
        man_phant_chooser[1] = new JCustom_layer_chooser("Layer2", man_phant_chooser, 1, man_phnt_visible[2]);
        jPanel8.add(man_phant_chooser[0]);
        jPanel8.add(man_phant_chooser[1]);
        jCustom_Base_Shot1.jLabel1.setText("Forward baseshot");
        jCustom_Base_Shot1.isForward = true;
        jCustom_Base_Shot2.jLabel1.setText("Reverse baseshot");
        jCustom_Base_Shot2.isForward = false;
        //jPanel6.remove(clc[0]);
        base_shot = find_baseShot(proj);

        phant_view = new JPhantoming_view(proj, color, is_visible, man_phnt_visible, base_shot);

        jCustom_Base_Shot1.setPhntViewer(phant_view);
        jCustom_Base_Shot2.setPhntViewer(phant_view);
        clc[0].setPhntViewer(phant_view);
        clc[1].setPhntViewer(phant_view);
        clc[0].setFineTuning(this);
        clc[1].setFineTuning(this);
        man_phant_chooser[0].setPhntViewer(phant_view);
        man_phant_chooser[1].setPhntViewer(phant_view);
        man_phant_chooser[0].setFineTuning(this);
        man_phant_chooser[1].setFineTuning(this);
        this.setProj(proj);
        init_status();

        jPanel5.add(phant_view);

    }

