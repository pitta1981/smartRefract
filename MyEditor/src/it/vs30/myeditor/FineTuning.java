    private int[] find_baseShot(Indagine proj) {
        int nshot = proj.stesa.size();
        double distanza_For = 999;
        double distanza_Rev = 999;
        int ind_For = 0;
        int ind_Rev = 0;
        for (int i = 0; i < nshot; i++) {
            FirstBrakeList fbl = proj.stesa.get(i);

            if (fbl.scoppio < fbl.spaz_in) {
                if (Math.abs(fbl.scoppio - fbl.spaz_in) < distanza_For) {
                    distanza_For = Math.abs(fbl.scoppio - fbl.spaz_in);
                    ind_For = i;

                }
            }

            if (fbl.scoppio > fbl.spaz_in + (fbl.spaz * (fbl.ch - 1))) {
                if (Math.abs(fbl.scoppio - fbl.spaz_in) < distanza_Rev) {
                    distanza_Rev = Math.abs(fbl.scoppio - fbl.spaz_in);
                    ind_Rev = i;

                }
            }

        }
        int[] a = {ind_For, ind_Rev};
        //To change body of generated methods, choose Tools | Templates.
        return a;
    }

